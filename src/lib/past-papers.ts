/** Every paper: flagships + dated sittings (v25 five-years-per-exam). */
export const PAST_PAPERS: PastPaper[] = [
  ...FLAGSHIPS,
  ...FAMILIES.flatMap((f) => sittingPapers(f)),
]

/** Families for the grouped UI: flagship + four dated sittings each. */
export const PAPER_FAMILIES: PaperFamily[] = FAMILIES.map((f) => {
  const flagship = FLAGSHIPS.find((p) => p.id === f.flagship)!
  return {
    id: f.base,
    titleEn: f.titleEn,
    titleAr: f.titleAr,
    group: f.group,
    flagship,
    sittings: sittingPapers(f),
  }
})

export function getPastPaper(id: string): PastPaper | null {
  return PAST_PAPERS.find((p) => p.id === id) ?? null
}
