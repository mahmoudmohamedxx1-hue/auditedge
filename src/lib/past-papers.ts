/** A family groups its flagship paper + the four dated sittings. */
export type PaperFamily = {
  id: string
  titleEn: string
  titleAr: string
  group: PaperGroup
  /** the flagship entry (the fullest paper) */
  flagship: PastPaper
  /** dated sittings, newest first */
  sittings: PastPaper[]
}

/** Build the dated-sitting paper entries for one family. */
function sittingPapers(f: FamilyDef): PastPaper[] {
  const count = f.sittingCount ?? 18
  const duration = Math.round(count * 3) // 18Q → 54 min, 15Q → 45 min
  return PAPER_SITTINGS.map((s) => ({
    id: `${f.base}-${s.slug}`,
    titleEn: `${f.titleEn} — ${s.label} sitting`,
    titleAr: `${f.titleAr} — جلسة ${s.labelAr}`,
    body: f.body,
    area: f.area,
    source: `${f.sourceLabel} — ${s.label} (adapted)`,
    count,
    durationMin: duration,
    difficulty: f.difficulty,
    group: f.group,
    blurbEn: `The ${s.label} sitting — ${count} fresh scenario questions in the ${f.titleEn} style.`,
    blurbAr: `جلسة ${s.labelAr} — ${count === 15 ? "١٥" : "١٨"} سؤال سيناريو جديد بأسلوب ${f.titleAr}.`,
  }))
}

